#!/usr/bin/env python3
"""Assemble the MIbandR vibe-player installer watchface.

Inputs (all under native/):
  out/vibe_player.elf                       payload built by build_payload.sh
  baseline/canopus_loader_profile-*.bin     machine-verified loader profile
  baseline/canopus_stage1-*.bin             machine-verified stage1 binary
  baseline/canopus_stage2-*.bin             machine-verified stage2 binary
  loader/recover_execute.lua                Lua bootstrap (recovery)
  loader/native_loader.lua                  NSH mw/exec ELF loader chain
  baseline/progress.lua                     async UI runner
  watchface/main.lua                        entry template with @MIBANDR_*@
  target/lua-recovery.toml                  recovery profile fields

Outputs: watchface/dist/ containing the .face zip content (main.lua plus
canopus_* resources). The payload keeps the resource slot name
"canopus_supervisor-<target>.bin" because the vendored loader writes it to
/data/canopus/supervisor.elf and its CRC is bound in the profile.

SPDX-License-Identifier: AGPL-3.0-or-later
"""
from __future__ import annotations

import json
import re
import shutil
import tomllib
import zlib
from pathlib import Path

NATIVE = Path(__file__).resolve().parents[1]
TARGET = "xiaomi-band-11-4.100.179"
FW_VERSION = "4.100.179"


def main() -> None:
    payload = (NATIVE / "out" / "vibe_player.elf").read_bytes()
    if payload[:4] != b"\x7fELF":
        raise SystemExit("payload is not an ELF file")

    # --- 1. stage resources from build_stages.py (stage1/stage2 rebuilt and
    # CRC-bound to this payload; profile generated with matching values)
    stages = NATIVE / "watchface" / "stages"
    profile_src = (stages / f"canopus_loader_profile-{TARGET}.bin").read_text()
    stage1 = (stages / f"canopus_stage1-{TARGET}.bin").read_bytes()
    stage2 = (stages / f"canopus_stage2-{TARGET}.bin").read_bytes()

    def field(name):
        return int(re.search(rf"{name} = (\d+)", profile_src).group(1))

    if len(stage1) != field("stage1_size") or zlib.crc32(stage1) != field("stage1_crc"):
        raise SystemExit("stages stage1 does not match profile size/CRC")
    if len(stage2) != field("stage2_size") or zlib.crc32(stage2) != field("stage2_crc"):
        raise SystemExit("stages stage2 does not match profile size/CRC")
    if len(payload) != field("supervisor_size") or zlib.crc32(payload) != field("supervisor_crc"):
        raise SystemExit("stages supervisor does not match payload size/CRC")

    # --- 2. recovery PROFILES injection from lua-recovery.toml
    rec = tomllib.loads((NATIVE / "target" / "lua-recovery.toml").read_text())
    rec_fields = ("target_id", "firmware_sha256", "firmware_version", "firmware_build",
                  "lua_version", "identity_path", "pmain", "pmain_error_handler",
                  "os_execute", "io_open")
    entries = "".join(
        f"    {key} = {hex(rec[key]) if isinstance(rec[key], int) else json.dumps(rec[key])},\n"
        for key in rec_fields
    )
    profiles_lua = "local PROFILES = {\n  [" + json.dumps(FW_VERSION) + "] = {\n" + entries + "  },\n}\n"

    # --- 3. inject main.lua
    src = (NATIVE / "watchface" / "main.lua").read_text()
    replacements = {
        "-- @MIBANDR_RECOVERY@": "local recovery = (function()\n"
            + (NATIVE / "loader" / "recover_execute.lua").read_text() + "\nend)()",
        "-- @MIBANDR_PROFILE@": profiles_lua,
        "-- @MIBANDR_NATIVE_LOADER@": "local native_loader = (function()\n"
            + (NATIVE / "loader" / "native_loader.lua").read_text() + "\nend)()",
        "-- @MIBANDR_PROGRESS@": "local progress = (function()\n"
            + (NATIVE / "baseline" / "progress.lua").read_text() + "\nend)()",
    }
    for marker, replacement in replacements.items():
        if src.count(marker) != 1:
            raise SystemExit(f"entry marker missing or repeated: {marker}")
        src = src.replace(marker, replacement)
    src = "-- Generated by native/scripts/build_installer.py; edit native/watchface/main.lua.\n" + src

    # --- 4. assemble dist/
    dist = NATIVE / "watchface" / "dist"
    if dist.exists():
        shutil.rmtree(dist)
    dist.mkdir(parents=True)
    (dist / "main.lua").write_text(src)
    (dist / f"canopus_loader_profile-{TARGET}.bin").write_text(profile_src)
    (dist / f"canopus_stage1-{TARGET}.bin").write_bytes(stage1)
    (dist / f"canopus_stage2-{TARGET}.bin").write_bytes(stage2)
    (dist / f"canopus_supervisor-{TARGET}.bin").write_bytes(payload)

    print(f"installer assembled in {dist}")
    for item in sorted(dist.iterdir()):
        print(f"  {item.name}: {item.stat().st_size} bytes")


if __name__ == "__main__":
    main()
