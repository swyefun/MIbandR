#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""wav_to_vibe.py — convert your own music (WAV) into a vibe waveform header.

Music through the Band 11 LRA is amplitude-envelope coding: the motor
resonates at a fixed ~250 Hz, so the waveform carries the song's RHYTHM
(1 ms segment timing) and LOUDNESS (per-segment amplitude 0..255), not pitch.

Usage:
    python wav_to_vibe.py song.wav --name "My Song" --macro MY_SONG --out extra.h

The script:
  1. reads the WAV (16-bit PCM, any sample rate; stereo is mixed to mono),
  2. computes an RMS loudness envelope in --frame ms windows,
  3. applies perceptual gamma (loud^0.7) so quiet parts stay audible,
  4. quantizes to 20 amplitude levels and merges runs (micro-gaps < 15 ms
     are folded into the previous tone),
  5. emits a static const struct vibe_segment array + count macro that you
     append to vibe-module/src/vibe_music.h and wire into the music page
     like the built-in tracks.

Keep songs under ~60 s: the generated array should stay below ~2000 segments
(firmware count limit is not yet device-verified beyond small waveforms).
FFmpeg can pre-convert mp3/m4a to wav:
    ffmpeg -i song.mp3 -ac 1 -ar 22050 song.wav
"""
import argparse
import math
import struct
import sys
import wave


def read_wav_mono(path):
    w = wave.open(path, "rb")
    nch, sw, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    raw = w.readframes(n)
    w.close()
    if sw == 2:
        samples = list(struct.unpack("<%dh" % (len(raw) // 2), raw))
    elif sw == 1:
        samples = [b - 128 for b in raw]
    elif sw == 4:
        samples = [x >> 16 for x in struct.unpack("<%di" % (len(raw) // 4), raw)]
    else:
        sys.exit("unsupported sample width %d" % sw)
    mono = []
    for i in range(0, len(samples) - nch + 1, nch):
        mono.append(sum(samples[i:i + nch]) / nch)
    return mono, rate


def rms_envelope(samples, rate, frame_ms):
    win = max(1, int(rate * frame_ms / 1000.0))
    env = []
    peak = 1e-9
    for i in range(0, len(samples) - win + 1, win):
        chunk = samples[i:i + win]
        r = math.sqrt(sum(x * x for x in chunk) / win)
        env.append(r)
        peak = max(peak, r)
    return [e / peak for e in env], win


def env_to_segments(env, frame_ms, levels=20):
    """Run-length encode the quantized loudness envelope into vibe segments.

    - loudness < 0.045 counts as silence (amplitude 0),
    - otherwise loud^0.7 perceptual gamma, quantized to `levels` steps,
    - micro-gaps (< 15 ms silence) are folded into the previous tone so
      articulation survives quantization noise.
    """
    step = 255.0 / levels
    runs = []                      # [amp, n_frames]
    for e in env:
        if e < 0.045:
            q = 0
        else:
            q = max(1, min(255, int(round(255.0 * (e ** 0.7) / step) * step)))
        q = int(q)
        if runs and runs[-1][0] == q:
            runs[-1][1] += 1
        else:
            runs.append([q, 1])
    folded = []
    for q, n in runs:
        dur = n * frame_ms
        if q == 0 and dur < 15 and folded and folded[-1][0] > 0:
            folded[-1][1] += n
        elif folded and folded[-1][0] == q:
            folded[-1][1] += n
        else:
            folded.append([q, n])
    return [(0, max(1, int(round(n * frame_ms))), 0, q) for q, n in folded]


def emit(name, macro, segs, duration_s, out_path):
    block = []
    block.append("")
    block.append("/* %s - %d segments, %.1f s (generated by wav_to_vibe.py) */" %
                 (name, len(segs), duration_s))
    block.append("static const struct vibe_segment s_TRACK_%s[] = {" % macro)
    for (o, d, f, a) in segs:
        block.append("    {%du, %du, 0u, %du}," % (o, d, a))
    block.append("};")
    block.append("#define TRACK_%s_COUNT (sizeof(s_TRACK_%s) / sizeof(s_TRACK_%s[0]))" %
                 (macro, macro, macro))
    with open(out_path, "a", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(block) + "\n")
    print("%s: %d segments, %.1f s, %d bytes -> %s" %
          (macro, len(segs), duration_s, len(segs) * 6, out_path))
    if len(segs) > 2000:
        print("WARNING: >2000 segments; firmware count limit unverified. "
              "Consider a shorter clip or --frame 40.")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("wav")
    ap.add_argument("--name", default="My Song")
    ap.add_argument("--macro", default="MY_SONG")
    ap.add_argument("--frame", type=int, default=25, help="envelope frame ms (default 25)")
    ap.add_argument("--out", default="vibe_music_extra.h")
    a = ap.parse_args()

    samples, rate = read_wav_mono(a.wav)
    env, _ = rms_envelope(samples, rate, a.frame)
    segs = env_to_segments(env, a.frame)
    emit(a.name, a.macro.upper(), segs, len(samples) / float(rate), a.out)
