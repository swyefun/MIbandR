#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_man_track.py — convert the user's song (Man) into vibe waveform arrays.

Improvements over the plain RMS envelope for dense pop mixes:
  - percentile normalization (90th percentile -> amplitude 255) so the loud
    sections use the full 0..255 range and quiet intros stay audible,
  - onset accents: a segment whose amplitude jumps by >60 over the previous
    one and lasts >=60 ms is split into a 30 ms FULL-amplitude accent pulse
    followed by the remainder — this restores the drum-hit transient feel
    that pure RMS flattens away,
  - trailing silence trimmed.

Outputs appended to vibe-module/src/vibe_music.h (before #endif):
  s_TRACK_MAN_FULL - the whole track, frame=25 ms  (~114 s of music)
  s_TRACK_MAN_CLIP - excerpt 20..56 s (loud chorus section), frame=20 ms
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from wav_to_vibe import read_wav_mono, rms_envelope  # noqa: E402

FRAME_MS_FULL = 25
FRAME_MS_CLIP = 20
CLIP_START_S = 20.0
CLIP_END_S = 56.0
LEVELS = 20
GAMMA = 0.6
SILENCE = 0.045


def envelope_to_runs(env, frame_ms):
    """Returns (runs, onset_flags) - onset_flags[i] True if frame i starts a
    percussive transient (large frame-to-frame loudness jump)."""
    step = 255.0 / LEVELS
    runs = []
    onsets = []
    for i, e in enumerate(env):
        on = (i > 0 and e - env[i - 1] > 0.15 and e > 0.30)
        onsets.append(on)
        if e < SILENCE:
            q = 0
        else:
            q = max(1, min(255, int(round(255.0 * (e ** GAMMA) / step) * step)))
            q = int(q)
        if runs and runs[-1][0] == q:
            runs[-1][1] += 1
        else:
            runs.append([q, 1, on])   # [amp, n_frames, starts_on_onset]
    return runs


def runs_to_segments(runs, frame_ms):
    segs = []
    for q, n, on in runs:
        dur = max(1, int(round(n * frame_ms)))
        segs.append([0, dur, 0, q, on])
    return segs


def add_onset_accents(segs):
    """Split onset segments: 30 ms full-amplitude accent + remainder. This
    restores the drum-hit transient that RMS flattens away."""
    out = []
    accents = 0
    for s in segs:
        amp, dur, on = s[3], s[1], s[4]
        if on and amp > 90 and dur >= 60:
            out.append([0, 30, 0, 255, False])
            out.append([0, dur - 30, 0, amp, False])
            accents += 1
        else:
            out.append([s[0], dur, s[2], amp, False])
    print("  accents inserted: %d" % accents)
    return out


def normalize(env):
    """Normalize by the 90th percentile so the loud body reaches full scale."""
    es = sorted(x for x in env if x > SILENCE)
    if not es:
        return env
    p90 = es[int(len(es) * 0.9)]
    return [min(1.0, x / p90) for x in env]


def trim_tail(segs):
    while segs and segs[-1][3] == 0:
        segs.pop()
    return segs


def emit(f, macro, segs, name):
    print("%s: %d segments, %.1f s, %d bytes" %
          (macro, len(segs), sum(s[1] for s in segs) / 1000.0, len(segs) * 6))
    f.write("/* %s - %d segments, %.1f s (generated by tools/gen_man_track.py) */\n"
            % (name, len(segs), sum(s[1] for s in segs) / 1000.0))
    f.write("static const struct vibe_segment s_TRACK_%s[] = {\n" % macro)
    for (_o, d, _fl, a, _on) in segs:
        f.write("    {0u, %du, 0u, %du},\n" % (d, a))
    f.write("};\n")
    f.write("#define TRACK_%s_COUNT (sizeof(s_TRACK_%s) / sizeof(s_TRACK_%s[0]))\n\n"
            % (macro, macro, macro))


def main():
    wav = os.path.join(HERE, "..", "..", "man_mono.wav")
    samples, rate = read_wav_mono(os.path.normpath(wav))

    hdr = os.path.normpath(os.path.join(HERE, "..", "src", "vibe_music.h"))
    text = open(hdr, encoding="utf-8").read()
    marker = "#endif /* VIBE_MUSIC_H */"
    assert marker in text, "marker missing"
    head = text[:text.index(marker)].rstrip("\n")
    if "s_TRACK_MAN_FULL" in head:
        sys.exit("Man tracks already present in vibe_music.h; regenerate cleanly first.")

    with open(hdr, "w", encoding="utf-8", newline="\n") as f:
        f.write(head + "\n\n")

        # --- full track ---
        env, _ = rms_envelope(samples, rate, FRAME_MS_FULL)
        env = normalize(env)
        segs = runs_to_segments(envelope_to_runs(env, FRAME_MS_FULL), FRAME_MS_FULL)
        print("full track:")
        segs = trim_tail(add_onset_accents(segs))
        emit(f, "MAN_FULL", segs, "Man full")

        # --- chorus excerpt 20..56 s at finer resolution ---
        i0 = int(CLIP_START_S * rate)
        i1 = min(len(samples), int(CLIP_END_S * rate))
        env2, _ = rms_envelope(samples[i0:i1], rate, FRAME_MS_CLIP)
        env2 = normalize(env2)
        segs2 = runs_to_segments(envelope_to_runs(env2, FRAME_MS_CLIP), FRAME_MS_CLIP)
        print("clip 20-56s:")
        segs2 = add_onset_accents(segs2)
        emit(f, "MAN_CLIP", segs2, "Man chorus 20-56s")

        f.write(marker + "\n")
    print("header updated:", hdr)


if __name__ == "__main__":
    main()
