#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_music.py — synthesize "music" waveforms for the vibe_player module.

The Band 11 LRA motor runs at a fixed resonance (~250-260 Hz, device-probed),
so pitch is NOT controllable. Music is conveyed the way it is through any
LRA haptic engine: RHYTHM via segment timing (1 ms granularity, verified down
to 1 ms on-device) and DYNAMICS via per-segment amplitude (verified sweep
16..255 changes loudness). Melodies remain recognizable through their rhythm
and stress pattern, exactly like classic "vibration melodies".

Each note becomes 4 segments: attack (6 ms, full amp) / body / decay
(12 ms, amp/3) / gap (silence). The attack+decay shape keeps the LRA from
ringing through note boundaries (staccato articulation).

Output: vibe-module/src/vibe_music.h with static const segment arrays and
count macros. Data budget is tiny (~600 segments * 6 bytes = 3.6 KB).
"""
import os

ATTACK_MS = 6
DECAY_MS = 12

# pitch name -> semitone index (used for amplitude shading: higher = louder)
PITCH = {"C": 0, "D": 1, "E": 2, "F": 3, "G": 4, "A": 5, "B": 6}


class Track:
    def __init__(self, name, macro):
        self.name = name
        self.macro = macro
        self.segs = []       # list of (offset, dur, flags, amp)
        self.total_ms = 0

    def note(self, slot_ms, body_ms, amp):
        """One articulated note inside a slot of slot_ms total."""
        gap = slot_ms - (ATTACK_MS + body_ms + DECAY_MS)
        if gap < 0:
            body_ms = slot_ms - ATTACK_MS - DECAY_MS
            gap = 0
        a = max(1, min(255, int(amp)))
        self.segs.append((0, ATTACK_MS, 0, a))
        if body_ms > 0:
            self.segs.append((0, body_ms, 0, a))
        self.segs.append((0, DECAY_MS, 0, max(50, a // 3)))
        if gap > 0:
            self.segs.append((0, gap, 0, 0))
        self.total_ms += slot_ms

    def rest(self, slot_ms):
        if slot_ms > 0:
            self.segs.append((0, slot_ms, 0, 0))
            self.total_ms += slot_ms

    def melody(self, notes, beat_ms, base_amp=200, amp_step=9):
        """notes: list of (pitch, beats); pitch 0 == base amplitude."""
        for pitch, beats in notes:
            slot = int(round(beat_ms * beats))
            body = slot - ATTACK_MS - DECAY_MS - 42   # 42 ms articulation gap
            amp = base_amp + pitch * amp_step
            self.note(slot, max(20, body), amp)

    def drum_pattern(self, bpm, bars, pattern):
        """pattern: string of 8 chars per bar: K=kick S=snare h=hat .=rest"""
        eighth = 60000.0 / bpm / 2.0
        for _ in range(bars):
            for ch in pattern:
                slot = int(round(eighth))
                if ch == "K":      # kick: fat 40 ms thump + decay
                    self.note(slot, 40, 255)
                elif ch == "S":    # snare: 25 ms crack + fast fall
                    self.note(slot, 25, 235)
                elif ch == "h":    # hi-hat: 10 ms tick
                    self.note(slot, 10, 150)
                else:
                    self.rest(slot)


def twinkle():
    """Twinkle Twinkle Little Star, C major, quarter = 420 ms."""
    t = Track("Little Star", "TRACK_LITTLE_STAR")
    q = 420
    phrase = [("C", 1), ("C", 1), ("G", 1), ("G", 1), ("A", 1), ("A", 1), ("G", 2),
              ("F", 1), ("F", 1), ("E", 1), ("E", 1), ("D", 1), ("D", 1), ("C", 2)]
    notes = []
    for _ in range(3):          # (A A B) x3 is the complete song
        notes += phrase
    t.melody([(PITCH[p], b) for p, b in notes], q)
    return t


def ode_to_joy():
    """Ode to Joy, C major, quarter = 300 ms (eighth = 150 ms)."""
    t = Track("Ode to Joy", "TRACK_ODE_TO_JOY")
    q = 300
    q2 = q // 2
    A1 = [("E", 1), ("E", 1), ("F", 1), ("G", 1),
          ("G", 1), ("F", 1), ("E", 1), ("D", 1),
          ("C", 1), ("C", 1), ("D", 1), ("E", 1),
          ("E", 1.5), ("D", 0.5), ("D", 2)]
    A2 = A1[:11] + [("D", 1.5), ("C", 0.5), ("C", 2)]      # ...D. C C(hold)
    # canonical form: A A' B A'
    notes = []
    notes += A1
    notes += A2
    # B section (dotted rhythm, low G lift at the end)
    notes += [("D", 1), ("D", 1), ("E", 1), ("C", 1),
              ("D", 1), ("E", 0.5), ("F", 0.5), ("E", 1), ("C", 1),
              ("D", 1), ("E", 0.5), ("F", 0.5), ("E", 1), ("D", 1),
              ("C", 1), ("D", 1), ("G", 2)]
    notes += A2
    t.melody([(PITCH[n[0]], n[1]) for n in notes], q)
    return t


def drum_beat():
    """110 BPM rock backbeat, 8 bars of K . h . S . h . (8 eighths/bar)."""
    t = Track("Drum Beat", "TRACK_DRUM_BEAT")
    t.drum_pattern(110, 8, "K.h.Sh.h.")
    return t


def emit(tracks, out_path):
    lines = []
    lines.append("/* vibe_music.h - GENERATED by tools/gen_music.py, do not edit by hand.")
    lines.append(" *")
    lines.append(" * Amplitude-envelope music for the Band 11 LRA (fixed ~250 Hz resonance).")
    lines.append(" * Rhythm = segment timing, dynamics = per-segment amplitude. The firmware")
    lines.append(" * accepts these counts whole (device-verified up to 32; music tracks stay")
    lines.append(" * under 700 segments and report rc via the UI status line).")
    lines.append(" */")
    lines.append("#ifndef VIBE_MUSIC_H")
    lines.append("#define VIBE_MUSIC_H")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    for t in tracks:
        lines.append("/* %s - %d segments, %.1f s */" %
                     (t.name, len(t.segs), t.total_ms / 1000.0))
        lines.append("static const struct vibe_segment s_%s[] = {" % t.macro)
        for (off, dur, fl, amp) in t.segs:
            lines.append("    {%du, %du, 0u, %du}," % (off, dur, amp))
        lines.append("};")
        lines.append("#define %s_COUNT (sizeof(s_%s) / sizeof(s_%s[0]))" %
                     (t.macro, t.macro, t.macro))
        lines.append("")
    lines.append("#endif /* VIBE_MUSIC_H */")
    text = "\n".join(lines) + "\n"
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    for t in tracks:
        print("%-16s %4d segments  %6.1f s  %5d bytes" %
              (t.macro, len(t.segs), t.total_ms / 1000.0,
               len(t.segs) * 6))


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(__file__), "..", "src", "vibe_music.h")
    emit([twinkle(), ode_to_joy(), drum_beat()], os.path.normpath(out))
