/* ---- generated amplitude-envelope music (tools/gen_music.py) ---- */
#include "vibe_music.h"

static struct vibe_waveform s_wave;
static struct vibe_params  s_params; /* static: zero-initialized */
static int32_t s_last_id;
static const struct canopus_context_v1 *s_ctx;
static const char *s_result = "点击按钮开始测试";
static int32_t s_result_rc;
static uint8_t  s_page; /* 0 = main, 1 = precision probe, 2 = music */

/* status line "<label> rc=<n>" rendered into a static buffer (no libc) */
static char s_status_buf[72];
static void set_status(const char *label, int32_t rc)
{
    uint32_t n = 0, i, t;
    char tmp[12];
    int32_t v = rc;
    while (label[n] != 0 && n < 48u) { s_status_buf[n] = label[n]; n++; }
    s_status_buf[n++] = ' ';
    s_status_buf[n++] = 'r';
    s_status_buf[n++] = 'c';
    s_status_buf[n++] = '=';
    i = n;
    if (v < 0) { s_status_buf[i++] = '-'; v = -v; }
    t = 0;
    do { tmp[t++] = (char)('0' + (int)(v % 10)); v /= 10; } while (v != 0 && t < sizeof(tmp));
    while (t > 0) s_status_buf[i++] = tmp[--t];
    s_status_buf[i] = 0;
    s_result = s_status_buf;
    s_result_rc = rc;
}

static int32_t vibe_play(const struct vibe_segment *segments, uint32_t count)
{
    vibe_run_fn run = (vibe_run_fn)(uintptr_t)CANOPUS_SUP_VIBRATOR_RUN;
    int32_t id;

    s_wave.count = (int32_t)count;
    s_wave.segments = segments;
    s_params.type = 0u;
    s_params.priority = 0u;
    s_params.kind = VIBE_KIND_WAVEFORM;
    s_params.key = 0;
    s_params.data = (const void *)&s_wave;

    id = run(&s_params);
    if (id == VIBE_BUSY) return -16;    /* -EBUSY */
    if (id < 0) return id;
    s_last_id = id;
    return (int32_t)count;
}

static void vibe_stop_now(void)
{
    vibe_cancel_fn cancel = (vibe_cancel_fn)(uintptr_t)CANOPUS_SUP_VIBRATOR_CANCEL;
    if (s_last_id > 0) {
        cancel(s_last_id);
        s_last_id = 0;
    }
}

/* ---- portable UI (native-ui-lab pattern) ---- */

static uint32_t vlen(const char *s) { uint32_t n = 0; while (s[n]) n++; return n; }

static int32_t ui_action(struct canopus_ui_tree_v1 *t, uint32_t key,
                         const char *title, const char *detail, uint32_t event)
{
    struct canopus_ui_action_row_props_v1 p = {
        sizeof(p), title, vlen(title), detail, vlen(detail), event, 1u };
    return s_ctx->ui->action_row(t, key, &p);
}

static int32_t ui_status(struct canopus_ui_tree_v1 *t)
{
    struct canopus_ui_text_props_v1 p = {
        sizeof(p), s_result, vlen(s_result), CANOPUS_UI_TEXT_BODY };
    return s_ctx->ui->text(t, KEY_STATUS, &p);
}

static int32_t vibe_render(struct canopus_ui_context_v1 *ui)
{
    struct canopus_ui_tree_v1 *t;
    struct canopus_ui_navigation_page_props_v1 page = {
        sizeof(page), "MIbandR Vibe", vlen("MIbandR Vibe") };
    struct canopus_ui_navigation_page_props_v1 probe = {
        sizeof(probe), "精度探测", vlen("精度探测") };
    struct canopus_ui_navigation_page_props_v1 music = {
        sizeof(music), "音乐播放", vlen("音乐播放") };
    int32_t rc = s_ctx->ui->tree_begin(ui, &t);

    if (rc != 0) return rc;
    if (s_page == 0u) {
        if (rc == 0) rc = s_ctx->ui->navigation_page(t, 1u, &page);
        if (rc == 0) rc = ui_action(t, KEY_SWEEP, "扫幅度",
                                    "16/64/128/200/255 递增", CMD_SWEEP);
        if (rc == 0) rc = ui_action(t, KEY_PULSE, "短脉冲",
                                    "50/100/200/400 ms 全幅度", CMD_PULSE);
        if (rc == 0) rc = ui_action(t, KEY_STEADY, "恒振",
                                    "3 秒 全幅度 参考音", CMD_STEADY);
        if (rc == 0) rc = ui_action(t, KEY_STOP, "停止",
                                    "cancel 当前振动", CMD_STOP);
        if (rc == 0) rc = ui_action(t, KEY_GOPROBE, "精度探测 →",
                                    "时长下限/offset/flags", CMD_GOPROBE);
        if (rc == 0) rc = ui_action(t, KEY_GOMUSIC, "音乐播放 →",
                                    "小星星/欢乐颂/鼓点", CMD_GOMUSIC);
    } else if (s_page == 1u) {
        if (rc == 0) rc = s_ctx->ui->navigation_page(t, 2u, &probe);
        if (rc == 0) rc = ui_action(t, KEY_PROBE_DURATION, "① 时长下限",
                                    "100→50→20→10→5→2→1 ms", CMD_PROBE_DURATION);
        if (rc == 0) rc = ui_action(t, KEY_PROBE_OFFSET, "② offset 调度",
                                    "静默3s + 3脉冲@0.5/1.5/2.5s", CMD_PROBE_OFFSET);
        if (rc == 0) rc = ui_action(t, KEY_PROBE_FLAGS, "③ flags 位扫描",
                                    "0x01..0x80 间隔递增300→1000ms", CMD_PROBE_FLAGS);
        if (rc == 0) rc = ui_action(t, KEY_PROBE_FLAGSAB, "④ flags A/B",
                                    "30ms 参照vs该位 配对对比", CMD_PROBE_FLAGSAB);
        if (rc == 0) rc = ui_action(t, KEY_BACK, "← 返回",
                                    "回主页面", CMD_BACK);
    } else {
        if (rc == 0) rc = s_ctx->ui->navigation_page(t, 3u, &music);
        if (rc == 0) rc = ui_action(t, KEY_TRACK_MAN2_CLIP, "Man 副歌 HD",
                                    "分频DSP包络 20-56s", CMD_TRACK_MAN2_CLIP);
        if (rc == 0) rc = ui_action(t, KEY_TRACK_MAN2_FULL, "Man 全曲 HD",
                                    "分频DSP包络 约112秒", CMD_TRACK_MAN2_FULL);
        if (rc == 0) rc = ui_action(t, KEY_TRACK_STAR, "小星星",
                                    "节奏旋律 约20秒", CMD_TRACK_STAR);
        if (rc == 0) rc = ui_action(t, KEY_TRACK_ODE, "欢乐颂",
                                    "节奏旋律 约19秒", CMD_TRACK_ODE);
        if (rc == 0) rc = ui_action(t, KEY_TRACK_DRUM, "鼓点节拍",
                                    "110 BPM 底鼓/军鼓 约20秒", CMD_TRACK_DRUM);
        if (rc == 0) rc = ui_action(t, KEY_STOP, "停止",
                                    "cancel 当前振动", CMD_STOP);
        if (rc == 0) rc = ui_action(t, KEY_BACK, "← 返回",
                                    "回主页面", CMD_BACK);
    }
    if (rc == 0) rc = ui_status(t);
    if (rc == 0) rc = s_ctx->ui->end(t);
    if (rc == 0) rc = s_ctx->ui->tree_commit(t); else s_ctx->ui->tree_abort(t);
    return rc;
}

static int32_t vibe_on_open(const struct canopus_context_v1 *ctx,
                            struct canopus_ui_context_v1 *ui, void *user)
{
    (void)user;
    s_ctx = ctx;
    return vibe_render(ui);
}

static int32_t vibe_on_event(const struct canopus_context_v1 *ctx,
                             struct canopus_ui_context_v1 *ui,
                             const struct canopus_ui_event_v1 *e, void *user)
{
    int32_t rc;
    (void)user;
    if (e->type != CANOPUS_UI_EVENT_ACTIVATE) return 0;

    switch (e->event_id) {
    case CMD_SWEEP:  rc = vibe_play(s_scan, 9u);   set_status("扫幅度", rc);  return vibe_render(ui);
    case CMD_PULSE:  rc = vibe_play(s_pulse, 7u);  set_status("短脉冲", rc);  return vibe_render(ui);
    case CMD_STEADY: rc = vibe_play(s_steady, 1u); set_status("恒振", rc);    return vibe_render(ui);
    case CMD_PROBE_DURATION:
        rc = vibe_play(s_durlow, 13u); set_status("时长下限", rc); return vibe_render(ui);
    case CMD_PROBE_OFFSET:
        rc = vibe_play(s_offset, 4u);  set_status("offset调度", rc); return vibe_render(ui);
    case CMD_PROBE_FLAGS:
        rc = vibe_play(s_flags, 16u);  set_status("flags扫描", rc); return vibe_render(ui);
    case CMD_PROBE_FLAGSAB:
        rc = vibe_play(s_flagsab, 32u); set_status("flagsA/B", rc); return vibe_render(ui);
    case CMD_TRACK_STAR:
        rc = vibe_play(s_TRACK_LITTLE_STAR, (uint32_t)TRACK_LITTLE_STAR_COUNT);
        set_status("小星星", rc); return vibe_render(ui);
    case CMD_TRACK_ODE:
        rc = vibe_play(s_TRACK_ODE_TO_JOY, (uint32_t)TRACK_ODE_TO_JOY_COUNT);
        set_status("欢乐颂", rc); return vibe_render(ui);
    case CMD_TRACK_DRUM:
        rc = vibe_play(s_TRACK_DRUM_BEAT, (uint32_t)TRACK_DRUM_BEAT_COUNT);
        set_status("鼓点节拍", rc); return vibe_render(ui);
    case CMD_TRACK_MAN2_CLIP:
        rc = vibe_play(s_TRACK_MAN2_CLIP, (uint32_t)TRACK_MAN2_CLIP_COUNT);
        set_status("Man副歌", rc); return vibe_render(ui);
    case CMD_TRACK_MAN2_FULL:
        rc = vibe_play(s_TRACK_MAN2_FULL, (uint32_t)TRACK_MAN2_FULL_COUNT);
        set_status("Man全曲", rc); return vibe_render(ui);
    case CMD_STOP:
        vibe_stop_now();
        set_status("已停止", 0);
        return vibe_render(ui);
    case CMD_GOPROBE:
        s_page = 1u;
        return vibe_render(ui);
    case CMD_GOMUSIC:
        s_page = 2u;
        return vibe_render(ui);
    case CMD_BACK:
        s_page = 0u;
        return vibe_render(ui);
    default:
        return CANOPUS_UI_ERR_ARGUMENT;
    }
}

static int32_t vibe_on_back(const struct canopus_context_v1 *ctx,
                            struct canopus_ui_context_v1 *ui, void *user)
{
    (void)ctx; (void)user;
    if (s_page != 0u) {
        s_page = 0u;          /* probe/music page: back returns to the main page */
        return vibe_render(ui);
    }
    return 1; /* main page: close the page */
}

static void vibe_on_close(const struct canopus_context_v1 *ctx, void *user)
{
    (void)ctx; (void)user;
}

static const struct canopus_ui_entry_v1 s_ui_entry = {
    sizeof(s_ui_entry), "MIbandR Vibe",
    vibe_on_open, vibe_on_event, vibe_on_back, vibe_on_close,
    0, 0, 0, 0,
};

/* ---- launcher publication (ADR-CAN-011 single-page contract) ---- */

static const char s_app_label[] = "MIbandR Vibe";
static const char s_app_icon[] = "/data/canopus/manager_icon.bin";

static int32_t vibe_publish_native_app_stage(const struct canopus_context_v1 *ctx,
                                             uint32_t stage)
{
    if (stage == 1u) {
        struct canopus_app_entry_v1 entry;
        int32_t app_id;
        if (ctx->launcher == 0 || ctx->launcher->register_app == 0) {
            return CANOPUS_SVC_ERR_UNSUPPORTED;
        }
        /* page_count = 0: the launcher page binds this module's UI entry. */
        entry.struct_size = sizeof(entry);
        entry.label = s_app_label;
        entry.icon = s_app_icon;
        entry.pages = 0;
        entry.page_count = 0u;
        app_id = ctx->launcher->register_app(ctx, &entry);
        return app_id < 0 ? app_id : 0;
    }
    if (stage == 2u) return 0; /* no auto-navigation; the user opens the app */
    return CANOPUS_SVC_ERR_ARGUMENT;
}

/* ---- module lifecycle ---- */

static int32_t vibe_prepare(const struct canopus_context_v1 *ctx)
{
    s_ctx = ctx;
    s_last_id = 0;
    s_result_rc = 0;
    return 0;
}

static int32_t vibe_activate(const struct canopus_context_v1 *ctx)
{
    s_ctx = ctx;
    if (ctx->ui == 0 || ctx->ui->set_entry == 0) {
        return CANOPUS_SVC_ERR_UNSUPPORTED;
    }
    return ctx->ui->set_entry(ctx, &s_ui_entry);
}

static int32_t vibe_deactivate(const struct canopus_context_v1 *ctx)
{
    if (ctx != 0 && ctx->ui != 0 && ctx->ui->set_entry != 0) {
        (void)ctx->ui->set_entry(ctx, 0);
    }
    return 0;
}

static int32_t vibe_stop(const struct canopus_context_v1 *ctx)
{
    vibe_stop_now();
    return vibe_deactivate(ctx);
}

static int32_t vibe_query(struct canopus_status_writer_v1 *writer)
{
    /* zero-import target: status-writer helpers live in the supervisor
     * runtime and would be undefined imports here; keep the no-op that the
     * official all-services-test module uses. */
    (void)writer;
    return 0;
}

